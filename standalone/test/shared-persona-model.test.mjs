 const view=management.inspect(b,ref.id);assert.equal(view.persona,'共同人格');
 const page=view.pages.find(p=>p.name==='concepts/shared.md');
 management.savePage({key:b,personaId:ref.id,page:page.name,text:page.text+'\n来自群聊的新记忆',revision:page.revision});
 assert.match(original.pages().find(p=>p.name===page.name).text,/来自群聊/);
