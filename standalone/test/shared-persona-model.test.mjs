 const inboxA=new ChatInbox(dir,a),inboxB=new ChatInbox(dir,b,Date.now,ref.id);
 inboxA.append({sourceId:'only-private',sender:'100000002',text:'私聊现场'});assert.equal(inboxB.read().messages.length,0);
 original.record({id:'old-private',kind:'qq-input',sender:'100000002',text:'私聊待整理'});
 assert.ok(!JSON.stringify(startupSources(shared,inboxB,[])).includes('私聊待整理'));
